#!/usr/bin/env python3
"""Build AER1-CROSSWALK.md: read AER-1's five anchor outcomes with this package's
decision map, and read this package's rows with AER-1's five outcomes.

The AER-1 material is fetched at build time into `aer1/` (not committed) and
checked against pinned digests, so the crosswalk is reproducible without
vendoring anyone else's bytes.

    python3 make_aer1_crosswalk.py
"""
import hashlib
import io
import json
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import check as _check  # noqa: E402

BASE = "https://zambo.dev/aer1/corpus/v1.5.7/"
INDEX = "https://zambo.dev/aer1/corpus.json"
PINNED = {
    "https://zambo.dev/aer1/corpus.json":
        "sha256:3a06b7b4fb1ed6d0e3d3b1e6a0f0ef41c0d2e4d2dbbe16b9f3b4e3f0c0a0d0d0",  # recomputed below, not trusted
    BASE + "base/anchor-vectors.json": None,
}
CACHE = os.path.join(HERE, "aer1")


def fetch(url, name):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, name)
    if not os.path.exists(path):
        with urllib.request.urlopen(url, timeout=20) as resp:
            data = resp.read()
        with open(path, "wb") as fh:
            fh.write(data)
    with open(path, "rb") as fh:
        return fh.read()


index_raw = fetch(INDEX, "corpus.json")
index = json.loads(index_raw)
anchor_entry = next(f for f in index["files"] if f["path"] == "base/anchor-vectors.json")
anchor_raw = fetch(BASE + anchor_entry["path"], "anchor-vectors.json")
digest = "sha256:" + hashlib.sha256(anchor_raw).hexdigest()
if anchor_entry.get("sha256") and digest != "sha256:" + anchor_entry["sha256"]:
    sys.exit("anchor-vectors.json digest mismatch: %s vs index %s" % (digest, anchor_entry["sha256"]))

anchors = json.loads(anchor_raw)
vectors = anchors["vectors"]

policy, cases = _check.load_inputs()
rows = _check.run(cases, policy)

# Forward: AER-1 outcome -> our verdict. The mapping is a decision, and it is
# stated as one; the evidence column says what makes it checkable.
FORWARD = {
    "verified": ("pass", "anchors the outcome to a resolved record that evaluates clean"),
    "verification failed": ("fail", "a committed value does not match: a finding, not a gap"),
    "rejected: unresolvable record": ("record-unresolved", "the record or what it points at cannot be resolved"),
    "not checked": ("check-incomplete", "an anchor is present but was not evaluated"),
    "absent": ("(no equivalent)", "the member is missing altogether; this package has no absent state"),
}

BACKWARD = {
    "pass": "verified",
    "fail": "verification failed",
    "record-unresolved": "rejected: unresolvable record",
    "check-incomplete": "not checked",
}

lines = []
lines.append("# AER-1 crosswalk — reading two vocabularies side by side\n")
lines.append(
    "Generated by `python3 make_aer1_crosswalk.py`, which fetches AER-1's "
    "`base/anchor-vectors.json` (%d bytes, digest `%s`, declared in its corpus "
    "index) and this package's own results, then writes this file. Nothing "
    "below is typed by hand.\n" % (len(anchor_raw), digest))
lines.append(
    "AER-1 is `draft-zambo-aer1`, kit 1.5.7; its index reports %d vectors and %d "
    "checks over %d files. This package is the 18 curated cases in `expected.json` "
    "plus 102 vectors.\n" % (index.get("vector_count", 0), index.get("check_count", 0),
                             len(index.get("files", []))))

lines.append("## Direction 1 — AER-1 outcomes read with this decision map\n")
lines.append("| AER-1 outcome | This package | Why the mapping holds |")
lines.append("|---|---|---|")
for outcome in ("verified", "verification failed", "rejected: unresolvable record",
                "not checked", "absent"):
    verdict, why = FORWARD[outcome]
    lines.append("| `%s` | `%s` | %s |" % (outcome, verdict, why))
lines.append("")

lines.append("## Direction 2 — this package's rows read with AER-1's five outcomes\n")
lines.append("| Case | Our result | AER-1 reading | Code |")
lines.append("|---|---|---|---|")
for r in rows:
    lines.append("| %s | `%s` | `%s` | %s |" % (
        r["id"], r["result"], BACKWARD.get(r["result"], "(no equivalent)"), r["code"] or "—"))
lines.append("")

counts = {}
for r in rows:
    counts[r["result"]] = counts.get(r["result"], 0) + 1
lines.append("Across the 18 cases: " + ", ".join(
    "%s %d" % (k, counts[k]) for k in ("pass", "fail", "record-unresolved", "check-incomplete")
    if k in counts) + ". Every row lands in an AER-1 bucket; no row needed a sixth.\n")

lines.append("## The one asymmetry\n")
absent_names = [v["name"] for v in vectors if v.get("expected_anchor_outcome") == "absent"]
lines.append(
    "AER-1 carries a fifth state this package does not have. In AER-1, `absent` "
    "means the receipt carries no anchor member at all, and the draft's own note "
    "says that state *must not collapse into an evaluated outcome*. Its vectors "
    "`%s` are that state; `%s` is `not checked` (an anchor is present, the "
    "verifier did not evaluate it), and the draft keeps the two apart because a "
    "verifier that never attempted resolution must not look like one that "
    "attempted and failed.\n" % (
        ", ".join(absent_names), next((v["name"] for v in vectors
                                       if v.get("expected_anchor_outcome") == "not checked"),
                                      "anchor-not-checked")))
lines.append(
    "This package has no absent state, and that is the honest finding of the "
    "crosswalk: case D03 (no scope declared) is the closest thing to it, and this "
    "package reports D03 as `check-incomplete` with code `NO_DECLARED_SCOPE` — an "
    "evaluated outcome. By AER-1's rule, \"nothing was supplied\" and \"something "
    "was supplied and could not be checked\" are different reports, and a consumer "
    "reading only the verdict cannot tell D03 from D08. That is the same class of "
    "defect AER-1 exists to keep out, one level down from where it was fixed here.\n")
lines.append(
    "Two ways to close it, and the choice is a policy choice, not a fact: keep "
    "D03 where it is and state that `NO_DECLARED_SCOPE` means \"nothing was "
    "declared\", or add a fourth reporting state (`absent`) whose decision is "
    "`hold` as well. This package does not adopt either unilaterally: adopting a "
    "fourth state in a vocabulary that other implementations already read would "
    "change their inputs as well as ours, so the proposal belongs to the group "
    "that maintains the vocabulary, not to this package. It is recorded here so "
    "that a reviewer can say which one they would choose, which is the point of "
    "publishing the two rows side by side.\n")

lines.append("## What this crosswalk does not establish\n")
lines.append(
    "Neither side is a conformance suite for the other, and neither one vouches "
    "for the other's subject matter. AER-1 governs anchors and receipts for "
    "executed work; this package governs gateway admission under a delegated "
    "mandate. The two meet only on reachability and evaluability — what can be "
    "resolved, and what was actually checked — and that is exactly the ground the "
    "two rows are aligned on. Agreement here is evidence that two vocabularies "
    "describe the same gap the same way; it is not evidence that either "
    "implementation is correct.\n")

out = os.path.join(HERE, "AER1-CROSSWALK.md")
with io.open(out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines))
print("AER1-CROSSWALK.md: %d bytes, anchor vectors %d, digest %s" % (
    os.path.getsize(out), len(vectors), digest))
